import fs from "node:fs";
import path from "node:path";
import YAML from "yaml";
import { CanonicalTool } from "../schemas/agent.js";
import { GardenConfig } from "../schemas/config.js";
import { loadConfig } from "./config.js";
import { listAgents, listCommands } from "./agents.js";

const PI_TOOLS: Record<CanonicalTool, string> = {
  read: "read",
  search: "grep",
  glob: "find",
  list: "ls",
  write: "write",
  edit: "edit",
  bash: "bash",
  dispatch: "subagent",
};

const CLAUDE_TOOLS: Record<CanonicalTool, string> = {
  read: "Read",
  search: "Grep",
  glob: "Glob",
  list: "Glob",
  write: "Write",
  edit: "Edit",
  bash: "Bash",
  dispatch: "Task",
};

function renderGenerated(
  data: Record<string, unknown>,
  body: string,
  source: string,
): string {
  const yaml = YAML.stringify(data).trimEnd();
  return `---\n# Generated by garden sync from ${source}. Do not edit.\n${yaml}\n---\n\n${body.replace(/^\n+/, "").trimEnd()}\n`;
}

function mapModel(
  model: string,
  adapter: "pi" | "claude",
  config: GardenConfig,
): string | undefined {
  if (model === "inherit") return undefined;

  const aliases = config.adapters[adapter]?.model_aliases ?? {};
  const mapped = aliases[model];
  if (!mapped) {
    throw new Error(
      `No model alias "${model}" for adapter ${adapter}. Add it to garden.toml.`,
    );
  }
  return mapped;
}

function mapTools(
  tools: CanonicalTool[],
  adapter: "pi" | "claude",
): string {
  const table = adapter === "pi" ? PI_TOOLS : CLAUDE_TOOLS;
  return Array.from(new Set(tools.map((tool) => table[tool]))).join(", ");
}

export function generatePi(root: string, config = loadConfig(root)): Map<string, string> {
  const generated = new Map<string, string>();

  for (const agent of listAgents(root)) {
    const data: Record<string, unknown> = {
      name: agent.meta.name,
      description: agent.meta.description,
      tools: mapTools(agent.meta.tools, "pi"),
    };
    const model = mapModel(agent.meta.model, "pi", config);
    if (model) data.model = model;

    generated.set(
      `.pi/agents/${agent.meta.name}.md`,
      renderGenerated(data, agent.body, agent.relFile),
    );
  }

  for (const command of listCommands(root)) {
    const data: Record<string, unknown> = {
      description: command.meta.description,
    };
    if (command.meta["argument-hint"]) {
      data["argument-hint"] = command.meta["argument-hint"];
    }

    generated.set(
      `.pi/prompts/${command.name}.md`,
      renderGenerated(data, command.body, command.relFile),
    );
  }

  return generated;
}

