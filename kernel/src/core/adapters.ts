export function generateAll(root: string, config = loadConfig(root)): Map<string, string> {
  const generated = new Map<string, string>();

  if (config.adapters.pi?.enabled ?? false) {
    for (const [file, content] of generatePi(root, config)) {
      generated.set(file, content);
    }
  }

  if (config.adapters.claude?.enabled ?? false) {
    for (const [file, content] of generateClaude(root, config)) {
      generated.set(file, content);
    }
  }

  return generated;
}

export interface SyncResult {
  written: string[];
  drifted: string[];
}

export function sync(
  root: string,
  options: { check?: boolean } = {},
  config = loadConfig(root),
): SyncResult {
  const generated = generateAll(root, config);
  const written: string[] = [];
  const drifted: string[] = [];

  for (const [relative, content] of generated) {
    const file = path.join(root, relative);

    if (options.check) {
      const existing = fs.existsSync(file)
        ? fs.readFileSync(file, "utf8")
        : null;
      if (existing !== content) {
        drifted.push(relative);
      }
    } else {
      fs.mkdirSync(path.dirname(file), { recursive: true });
      fs.writeFileSync(file, content, "utf8");
      written.push(relative);
    }
  }

  return { written, drifted };
}
